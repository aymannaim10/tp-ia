const { chromium } = require('@playwright/test');
const { default: AxeBuilder } = require('@axe-core/playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1050},permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.BASE_URL||'http://127.0.0.1:4173';
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('h1').waitFor();
 assert.equal(await page.locator('.phase-card').count(),6);
 fs.mkdirSync('.qa',{recursive:true});
 await page.screenshot({path:'.qa/desktop.png',fullPage:true});
 const audit=[];
 async function checkA11y(label){const a=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();audit.push({page:label,violations:a.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>n.target)}))});}
 await checkA11y('Accueil desktop');
 await page.locator('.hero-actions .primary').click();
 assert.match(await page.locator('h1').innerText(),/Votre premier notebook/);
 await page.locator('#copy-code').click();
 const copied=await page.evaluate(()=>navigator.clipboard.readText());
 assert.match(copied,/import sys/);
 await page.locator('#complete').click();
 assert.equal(await page.locator('#progress-count').innerText(),'1 / 24');
 await page.reload();
 assert.equal(await page.locator('#complete').getAttribute('aria-pressed'),'true');
 await checkA11y('Étape 1');
 assert.equal(await page.locator('.correction').getAttribute('open'),null);
 await page.locator('.correction summary').click();
 assert.notEqual(await page.locator('.correction').getAttribute('open'),null);
 await page.locator('.mentor summary').click();
 assert.notEqual(await page.locator('.mentor details').getAttribute('open'),null);
 await page.locator('.correction summary').click();
 for(let i=1;i<=24;i++){
  await page.goto(base+'/#etape-'+i);
  await page.waitForFunction(n=>document.querySelector('.lesson-heading')?.textContent.includes('Étape '+String(n).padStart(2,'0')+' / 24'),i);
  assert.equal(await page.locator('.code-block').count(),1);
  assert.ok((await page.locator('pre').innerText()).length>50);
  assert.equal(await page.locator('.analysis-panel').count(),1);
  assert.equal(await page.locator('.correction').getAttribute('open'),null);
 }
 await page.goto(base+'/#etape-8');await page.locator('#complete').click();
 assert.equal(await page.locator('#complete').getAttribute('aria-pressed'),'false');
 await page.locator('#checkpoint-check').check();await page.locator('#complete').click();
 assert.equal(await page.locator('#complete').getAttribute('aria-pressed'),'true');
 await page.goto(base+'/#etape-13');await page.screenshot({path:'.qa/lesson.png',fullPage:true});
 await checkA11y('Étape 13');
 await page.goto(base+'/#compte-rendu');
 assert.equal(await page.locator('tbody tr').count(),7);
 await checkA11y('Compte rendu');
 const downloadPromise=page.waitForEvent('download');await page.locator('a[download]').click();const download=await downloadPromise;
 assert.equal(download.suggestedFilename(),'TP1_Regression_Lineaire.ipynb');
 const notebook=await context.request.get(base+'/TP1_Regression_Lineaire.ipynb');assert.equal(notebook.status(),200);
 const nb=await notebook.json();assert.equal(nb.nbformat,4);assert.equal(nb.cells.filter(c=>c.cell_type==='code').length,24);
 await page.goto(base+'/#ressources');
 await checkA11y('Ressources');
 const csv=await context.request.get(base+'/logements.csv');assert.equal(csv.status(),200);assert.equal((await csv.text()).trim().split('\n').length,21);
 await page.goto(base+'/#etape-999');assert.equal(await page.locator('.hero').count(),1);
 await page.locator('#reset').click();await page.locator('#cancel-reset').click();assert.equal(await page.locator('#progress-count').innerText(),'2 / 24');
 await page.locator('#reset').click();await page.locator('#confirm-reset').click();assert.equal(await page.locator('#progress-count').innerText(),'0 / 24');
 await page.setViewportSize({width:390,height:844});
 await page.goto(base);
 await page.screenshot({path:'.qa/mobile.png',fullPage:true});
 await checkA11y('Accueil mobile');
 await page.locator('#menu').click();assert.equal(await page.locator('#menu').getAttribute('aria-expanded'),'true');
 await page.locator('.nav-step[data-step="1"]').click();await page.waitForFunction(()=>document.querySelector('#menu').getAttribute('aria-expanded')==='false');assert.equal(await page.locator('#menu').getAttribute('aria-expanded'),'false');
 await checkA11y('Étape mobile');
 for(const route of ['','#etape-13','#compte-rendu','#ressources']){
  await page.goto(base+'/'+route);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'No horizontal page overflow '+route);
 }
 await page.setViewportSize({width:320,height:750});await page.goto(base+'/#etape-13');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'320px width');
 await page.setViewportSize({width:1280,height:800});
 await page.goto(base);await page.keyboard.press('Tab');
 assert.equal(await page.evaluate(()=>document.activeElement.className),'skip');
 const noStorage=await browser.newContext();await noStorage.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('disabled');}});});
 const blocked=await noStorage.newPage();await blocked.goto(base+'/#etape-1');await blocked.locator('#complete').click();assert.equal(await blocked.locator('#progress-count').innerText(),'1 / 24');await noStorage.close();
 assert.deepEqual(errors,[]);
 fs.writeFileSync('.qa/accessibility.json',JSON.stringify(audit,null,2));
 console.log(JSON.stringify({functional:'passed',jsErrors:errors,audits:audit},null,2));
 await browser.close();
 assert.equal(audit.reduce((n,a)=>n+a.violations.length,0),0,'Accessibility violations');
})().catch(e=>{console.error(e);process.exit(1);});